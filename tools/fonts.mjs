// Embeds the game's fonts into the page: writes src/fonts.css with the woff2 files as data URIs.
//   npm run fonts      (rebuilds index.html after)
// Nunito 700-900 (one variable file) and Rubik Bubbles 400, only the latin and cyrillic subsets, as Google Fonts serves
// them. Letters outside those subsets (ş, ə …) are drawn by a system font. Both families are under the SIL Open Font
// License 1.1, whose full texts are copied into the comment at the top of the file, so they ship inside the page.
// Needs the network; the page itself then makes no requests.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CSS = 'https://fonts.googleapis.com/css2?family=Nunito:wght@700..900&family=Rubik+Bubbles&display=swap';
const LICENSES = {
  Nunito: 'https://raw.githubusercontent.com/google/fonts/main/ofl/nunito/OFL.txt',
  'Rubik Bubbles': 'https://raw.githubusercontent.com/google/fonts/main/ofl/rubikbubbles/OFL.txt',
};
const SUBSETS = ['latin', 'cyrillic'];
// without a desktop Chrome user agent Google answers with ttf instead of woff2
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

async function get(url, as) {
  const r = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return as === 'bytes' ? Buffer.from(await r.arrayBuffer()) : r.text();
}

const css = await get(CSS);
// the answer is a list of "/* subset */ @font-face { … }" blocks
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)].map((m) => ({ subset: m[1], face: m[2] }));
const faces = [];
for (const family of Object.keys(LICENSES))
  for (const subset of SUBSETS) {
    const b = blocks.find((x) => x.subset === subset && x.face.includes(`'${family}'`));
    if (!b) throw new Error(`no ${subset} block for ${family} in the Google Fonts answer`);
    const url = (b.face.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
    if (!url) throw new Error(`no woff2 url for ${family} ${subset}`);
    const data = (await get(url, 'bytes')).toString('base64');
    const face = b.face.replace(/url\([^)]+\)/, `url(data:font/woff2;base64,${data})`).replace(/\s*\n\s*/g, '');
    faces.push(`/* ${family}, ${subset} */\n${face}`);
  }

let notice = '';
for (const [family, url] of Object.entries(LICENSES)) {
  const text = (await get(url)).replace(/\r\n/g, '\n').replace(/\*\//g, '* /').trim();
  notice += `\n\n=== ${family} ===\n\n${text}`;
}

const out = `/* GENERATED by tools/fonts.mjs: do not edit. Run \`npm run fonts\` to make it again.\n\nThe fonts below are used under the SIL Open Font License 1.1:${notice}\n*/\n${faces.join('\n')}\n`;
writeFileSync(join(root, 'src', 'fonts.css'), out);
console.log(`src/fonts.css written: ${(Buffer.byteLength(out) / 1024).toFixed(0)} KB, ${faces.length} faces`);
