// Builds index.html (one self-contained page) from src/. No dependencies.
//   node tools/build.mjs          write index.html
//   node tools/build.mjs --check  exit 1 if index.html is out of date
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8').replace(/\r\n/g, '\n');

// src/fonts.css (made by tools/fonts.mjs) carries the embedded fonts and goes first
const css = read('src/fonts.css').trimEnd() + '\n' + read('src/style.css').trimEnd();
// The fragments are pasted in file-name order into ONE block scope, so they share variables and the order matters.
const js = readdirSync(join(root, 'src/js'))
  .filter((f) => f.endsWith('.js'))
  .sort()
  .map((f) => read(`src/js/${f}`).trimEnd())
  .join('\n\n');

const banner = '<!-- GENERATED by tools/build.mjs from src/. Do not edit this file: change src/ and run `npm run build`. -->';
let html = read('src/index.html');
for (const mark of ['/*__CSS__*/', '/*__JS__*/'])
  if (html.split(mark).length !== 2) throw new Error(`src/index.html must contain ${mark} exactly once`);
html = html
  .replace('<!DOCTYPE html>\n', `<!DOCTYPE html>\n${banner}\n`)
  .replace('/*__CSS__*/', () => css)
  .replace('/*__JS__*/', () => js);

const out = join(root, 'index.html');
if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== html) {
    console.error('index.html is out of date: run `npm run build`');
    process.exit(1);
  }
  console.log('index.html is up to date');
} else {
  writeFileSync(out, html);
  console.log(`index.html written: ${(Buffer.byteLength(html) / 1024).toFixed(0)} KB`);
}
